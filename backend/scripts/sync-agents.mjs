import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(resolve(root, '.agents/manifest.json'), 'utf8'));
const check = process.argv.includes('--check');
let mismatch = false;
function emit(path, text) {
  const file = resolve(root, path);
  if (check) {
    let actual;
    try {
      actual = readFileSync(file, 'utf8');
    } catch {
      actual = '';
    }
    if (actual !== text) {
      console.error(`Agent adapter drift: ${path}`);
      mismatch = true;
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}
const json = (value) => JSON.stringify(value, null, 2) + '\n';
const hookCommand = 'node "$(git rev-parse --show-toplevel)/backend/scripts/agent-hook.mjs"';
const hooks = Object.fromEntries(
  ['PreToolUse', 'PostToolUse', 'Stop'].map((event) => [
    event,
    [
      {
        ...(event !== 'Stop'
          ? { matcher: event === 'PreToolUse' ? '.*' : 'Edit|Write|apply_patch' }
          : {}),
        hooks: [{ type: 'command', command: hookCommand, timeout: event === 'Stop' ? 130 : 65 }],
      },
    ],
  ]),
);
emit(
  'CLAUDE.md',
  '@AGENTS.md\n\nShared skills and workflows: .agents/. Native adapter details: doc/agentic-setup.md.\n',
);
for (const folder of ['backend', 'site', 'mobile', 'doc'])
  emit(`${folder}/CLAUDE.md`, `@AGENTS.md\n`);
emit(
  '.claude/settings.json',
  json({
    permissions: {
      allow: [
        'Bash(npm run check)',
        'Bash(npm run check:fast)',
        'Bash(npm test)',
        'Bash(npm run lint)',
        'Bash(npm run typecheck)',
        'Bash(npm run build)',
        'Bash(npm run emulators)',
      ],
      ask: [
        'Bash(npm install *)',
        'Bash(npm ci *)',
        'Bash(git push *)',
        'Bash(firebase deploy *)',
        'WebFetch',
        'WebSearch',
      ],
      deny: [
        'Read(**/.env)',
        'Read(**/.env.local)',
        'Read(**/.env.production)',
        'Read(**/*.pem)',
        'Read(**/*service-account*)',
        'Edit(doc/contracts/generated/**)',
        'Bash(git push --force *)',
        'Bash(git push -f *)',
      ],
    },
    hooks,
  }),
);
let codex =
  '# Generated by npm run agents:sync. Shared source: .agents/.\napproval_policy = "on-request"\nsandbox_mode = "workspace-write"\n\n[sandbox_workspace_write]\nnetwork_access = false\n\n[features]\nhooks = true\n';
for (const [event, groups] of Object.entries(hooks)) {
  codex += `\n[[hooks.${event}]]\n`;
  if (groups[0].matcher) codex += `matcher = ${JSON.stringify(groups[0].matcher)}\n`;
  codex += `[[hooks.${event}.hooks]]\ntype = "command"\ncommand = ${JSON.stringify(hookCommand + ' codex')}\ntimeout = ${event === 'Stop' ? 130 : 65}\n`;
}
const openCode = {
  $schema: 'https://opencode.ai/config.json',
  permissions: [
    { action: 'shell', resource: '*', effect: 'ask' },
    ...[
      'npm test',
      'npm run check',
      'npm run check:fast',
      'npm run lint',
      'npm run typecheck',
      'npm run build',
      'npm run emulators',
      'git status *',
      'git diff *',
    ].map((resource) => ({ action: 'shell', resource, effect: 'allow' })),
    ...['git push --force *', 'git push -f *', 'rm *'].map((resource) => ({
      action: 'shell',
      resource,
      effect: 'deny',
    })),
    { action: 'external_directory', resource: '*', effect: 'ask' },
    { action: 'webfetch', resource: '*', effect: 'ask' },
    { action: 'websearch', resource: '*', effect: 'ask' },
    ...['*.env', '*.env.*', '*.pem', '*service-account*', '*credentials*'].flatMap((resource) =>
      ['read', 'edit'].map((action) => ({ action, resource, effect: 'deny' })),
    ),
    ...['read', 'edit'].map((action) => ({ action, resource: '*.env.example', effect: 'allow' })),
    { action: 'edit', resource: 'doc/contracts/generated/*', effect: 'deny' },
  ],
  agents: {},
  commands: {},
};
for (const role of manifest.agents) {
  const body = readFileSync(resolve(root, `.agents/agents/${role.name}.md`), 'utf8');
  const instructions = `Read AGENTS.md and applicable local instructions.\n${body}`;
  const tools = role.readOnly ? 'Read, Grep, Glob' : 'Read, Grep, Glob, Edit, Write, Bash';
  emit(
    `.claude/agents/${role.name}.md`,
    `---\nname: ${role.name}\ndescription: ${JSON.stringify(role.description)}\ntools: ${tools}\n---\n\nRead .agents/agents/${role.name}.md and follow it.\n`,
  );
  codex += `\n[agents.${role.name.replaceAll('-', '_')}]\ndescription = ${JSON.stringify(role.description)}\nconfig_file = "agents/${role.name}.toml"\n`;
  emit(
    `.codex/agents/${role.name}.toml`,
    `sandbox_mode = "${role.readOnly ? 'read-only' : 'workspace-write'}"\ndeveloper_instructions = ${JSON.stringify(instructions)}\n`,
  );
  openCode.agents[role.name] = {
    description: role.description,
    mode: 'subagent',
    system: `Read .agents/agents/${role.name}.md and follow it.`,
    ...(role.readOnly
      ? {
          permissions: [
            { action: 'edit', resource: '*', effect: 'deny' },
            { action: 'shell', resource: '*', effect: 'deny' },
            { action: 'webfetch', resource: '*', effect: 'deny' },
            { action: 'websearch', resource: '*', effect: 'deny' },
          ],
        }
      : {}),
  };
}
for (const skill of manifest.skills) {
  const content = readFileSync(resolve(root, `.agents/skills/${skill}/SKILL.md`), 'utf8');
  // Generated copies accommodate tools that do not discover .agents/skills.
  emit(`.claude/skills/${skill}/SKILL.md`, content);
  emit(`.opencode/skills/${skill}/SKILL.md`, content);
}
for (const command of manifest.commands) {
  const body = readFileSync(resolve(root, `.agents/commands/${command}.md`), 'utf8');
  emit(`.claude/commands/${command}.md`, body);
  openCode.commands[command] = { description: `LessonBooks ${command}`, template: body };
}
emit('.codex/config.toml', codex);
emit('opencode.json', json(openCode));
if (mismatch) process.exitCode = 1;
else console.log(check ? 'Agent adapters match shared sources.' : 'Agent adapters generated.');
